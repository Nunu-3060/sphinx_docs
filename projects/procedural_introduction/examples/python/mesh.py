"""三角形メッシュの表現、OBJ 形式での保存、matplotlib による簡易表示。

メッシュは、頂点座標の配列 vertices (N, 3) と、各三角形の頂点番号の配列
faces (M, 3) で表す。三角形の頂点は、表から見て反時計回りに並べる。
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from common import FloatArray, IntArray


@dataclass
class Mesh:
    """三角形メッシュ。uvs は頂点ごとのテクスチャ座標 (N, 2) で、無くてもよい。"""

    vertices: FloatArray
    faces: IntArray
    uvs: FloatArray | None = None

    def face_normals(self) -> FloatArray:
        """各三角形の単位法線（2 辺の外積を正規化したもの）。"""
        a, b, c = (self.vertices[self.faces[:, k]] for k in range(3))
        normals = np.cross(b - a, c - a)
        lengths = np.linalg.norm(normals, axis=1, keepdims=True)
        result: FloatArray = normals / np.maximum(lengths, 1e-12)
        return result

    def vertex_normals(self) -> FloatArray:
        """各頂点の法線。頂点を共有する三角形の法線を面積で重み付けして平均する。"""
        a, b, c = (self.vertices[self.faces[:, k]] for k in range(3))
        weighted = np.cross(b - a, c - a)  # 長さが三角形の面積の 2 倍になる
        normals = np.zeros_like(self.vertices)
        for k in range(3):
            np.add.at(normals, self.faces[:, k], weighted)
        lengths = np.linalg.norm(normals, axis=1, keepdims=True)
        result: FloatArray = normals / np.maximum(lengths, 1e-12)
        return result

    def transformed(self, matrix: FloatArray | None = None, offset: Sequence[float] = (0.0, 0.0, 0.0)) -> Mesh:
        """頂点に 3×3 の行列 matrix を掛け、offset だけ平行移動したメッシュを返す。"""
        vertices = self.vertices if matrix is None else self.vertices @ np.asarray(matrix).T
        return Mesh(vertices + np.asarray(offset), self.faces.copy(), None if self.uvs is None else self.uvs.copy())


def merge(meshes: Sequence[Mesh]) -> Mesh:
    """複数のメッシュを 1 つにまとめる（頂点番号をずらして連結する）。"""
    vertices = []
    faces = []
    offset = 0
    for mesh in meshes:
        vertices.append(mesh.vertices)
        faces.append(mesh.faces + offset)
        offset += len(mesh.vertices)
    return Mesh(np.concatenate(vertices), np.concatenate(faces))


def write_obj(mesh: Mesh, path: Path) -> None:
    """メッシュを Wavefront OBJ 形式で保存する。法線と、あれば UV も書き出す。"""
    normals = mesh.vertex_normals()
    lines = ["# generated by procedural_introduction"]
    lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in mesh.vertices]
    lines += [f"vn {x:.6f} {y:.6f} {z:.6f}" for x, y, z in normals]
    if mesh.uvs is not None:
        lines += [f"vt {u:.6f} {v:.6f}" for u, v in mesh.uvs]
    for face in mesh.faces + 1:  # OBJ の頂点番号は 1 から始まる
        if mesh.uvs is not None:
            lines.append("f " + " ".join(f"{i}/{i}/{i}" for i in face))
        else:
            lines.append("f " + " ".join(f"{i}//{i}" for i in face))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def shade(
    normals: FloatArray, base: Sequence[float] | FloatArray, light: Sequence[float] = (0.4, -0.6, 0.7)
) -> FloatArray:
    """法線と光の向きから、面の明るさをランバート反射（拡散反射）で決めた色を返す。"""
    direction = np.asarray(light, dtype=np.float64)
    direction /= np.linalg.norm(direction)
    lambert = np.clip(normals @ direction, 0.0, 1.0)
    brightness = 0.35 + 0.65 * lambert  # 影の部分も真っ黒にならないように環境光を足す
    result: FloatArray = np.clip(np.asarray(base)[None, :] * brightness[:, None], 0.0, 1.0)
    return result


def draw_mesh(
    ax: Any,
    mesh: Mesh,
    color: Sequence[float] | FloatArray = (0.62, 0.72, 0.88),
    edgecolor: str | None = None,
    linewidth: float = 0.2,
) -> None:
    """matplotlib の 3D の軸 ax にメッシュを描く。

    color に (M, 3) の配列を渡すと、三角形ごとに色を変えられる（陰影はその色に掛かる）。
    """
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection

    triangles = mesh.vertices[mesh.faces]
    colors = np.asarray(color, dtype=np.float64)
    normals = mesh.face_normals()
    if colors.ndim == 1:
        facecolors = shade(normals, colors)
    else:
        facecolors = shade(normals, (1.0, 1.0, 1.0)) * colors
    collection = Poly3DCollection(
        triangles, facecolors=facecolors, edgecolors=edgecolor if edgecolor else facecolors, linewidths=linewidth
    )
    ax.add_collection3d(collection)


def fit_view(ax: Any, meshes: Sequence[Mesh], elev: float = 25.0, azim: float = -60.0) -> None:
    """3D の軸の範囲をメッシュに合わせ、縦横比を等しくして軸を消す。"""
    points = np.concatenate([mesh.vertices for mesh in meshes])
    low = points.min(axis=0)
    high = points.max(axis=0)
    center = (low + high) / 2.0
    radius = float((high - low).max()) / 2.0
    ax.set_xlim(center[0] - radius, center[0] + radius)
    ax.set_ylim(center[1] - radius, center[1] + radius)
    ax.set_zlim(center[2] - radius, center[2] + radius)
    ax.set_box_aspect((1.0, 1.0, 1.0))
    ax.view_init(elev=elev, azim=azim)
    ax.set_axis_off()
